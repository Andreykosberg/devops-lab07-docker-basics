#!/bin/bash -x
# Доп. задание. Скрипт обновления (пересоздания) сертификата:
# генерирует новый сертификат и даёт команду nginx внутри уже работающего
# контейнера перечитать конфигурацию/сертификат (reload), без пересоздания
# контейнера.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONTAINER_NAME="${1:-nginx-lab7-ssl-cont}"

# Пересоздаём сертификат (volume смотрит на эту же папку, поэтому
# контейнеру не нужно ничего перезапускать - файлы обновятся "на лету")
"$SCRIPT_DIR/generate_cert.sh"

# Даём nginx внутри контейнера команду перечитать конфигурацию и сертификат
docker exec "$CONTAINER_NAME" nginx -s reload

echo "Сертификат обновлён, nginx в контейнере $CONTAINER_NAME перечитал конфигурацию (reload)."
